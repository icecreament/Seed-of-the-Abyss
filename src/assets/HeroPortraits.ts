// Design coordinates use a 64×80 grid; half steps become true native detail pixels.
// Broad material planes come first. Small highlights never replace the silhouette.
function painter(pc: PixelCanvas) {
  const point = ([x, y]: Point): Point => [Math.round(x * 2), Math.round(y * 2)];
  const q = (color: string, ...points: Point[]) => polygon(pc, color, points.map(point));
  return {
    q,
    l: (color: string, ...points: Point[]) => {
      for (let i = 1; i < points.length; i++) line(pc, point(points[i - 1]), point(points[i]), color);
    },
    r: (color: string, x: number, y: number, w = 0.5, h = 0.5) =>
      q(color, [x,y], [x+w,y], [x+w,y+h], [x,y+h]),
  };
}

